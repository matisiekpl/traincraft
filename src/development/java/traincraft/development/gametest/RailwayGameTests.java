    /**
     * Every track type in the table, laid into a real world, writes exactly the blocks it says.
     *
     * <p>One test rather than thirty-four: the per-type assertions are already unit tests against
     * the fixtures, and what is under test here is the applier, which is the same code for all of
     * them. A loop that stops at the first failure names the type it stopped on, which is all a
     * per-type test would have told anyone.
     */
    private static void everyTrackTypePlaces(GameTestHelper helper) {
        int checked = 0;
        for (TrackType type : TrackType.values()) {
            for (int facing = 0; facing < 4; facing++) {
                TrackPlan plan = TrackPlanCatalog.get(type, facing);
                if (plan == null) {
                    continue;
                }
                BlockPos origin = helper.absolutePos(new BlockPos(1, 2, 1));
                clear(helper, origin, plan);

                traincraft.track.PlacementResult result =
                        TrackPlacer.place(helper.getLevel(), origin, type, facing);
                if (!result.placed()) {
                    throw new AssertionError(
                            type + " facing " + facing + " refused to place: " + result.reason());
                }
                for (Placement placement : plan.placements()) {
                    BlockPos at = origin.offset(placement.dx(), placement.dy(), placement.dz());
                    var block = helper.getLevel().getBlockState(at).getBlock();
                    boolean rail =
                            block instanceof TrackBlock || block instanceof TrackOccupancyBlock;
                    if (!rail) {
                        throw new AssertionError(
                                type
                                        + " facing "
                                        + facing
                                        + " left "
                                        + at
                                        + " as "
                                        + block
                                        + " rather than track");
                    }
                }
                Placement first = plan.get(0);
                traincraft.track.TrackBreaker.dismantle(
                        helper.getLevel(),
                        origin.offset(first.dx(), first.dy(), first.dz()),
                        false);
                for (Placement placement : plan.placements()) {
                    BlockPos at = origin.offset(placement.dx(), placement.dy(), placement.dz());
                    if (!helper.getLevel().getBlockState(at).isAir()) {
                        throw new AssertionError(
                                type
                                        + " facing "
                                        + facing
                                        + " left a block after dismantling at "
                                        + at);
                    }
                }
                checked++;
            }
        }
        if (checked < 100) {
            throw new AssertionError(
                    "only "
                            + checked
                            + " type/facing pairs were placed;"
                            + " the table should hold hundreds");
        }
        helper.succeed();
    }

    private static void stockIsAlignedWhenPlaced(GameTestHelper helper) {
        BlockPos origin = helper.absolutePos(new BlockPos(5, 2, 5));
        Player player = helper.makeMockPlayer(net.minecraft.world.level.GameType.CREATIVE);
        var items = java.util.List.of(
                traincraft.bootstrap.ItemRegistry.LOCO_STEAM_ALICE.get(),
                traincraft.bootstrap.ItemRegistry.LOCO_STEAM_BR80.get(),
                traincraft.bootstrap.ItemRegistry.FREIGHT_CART_YELLOW.get());
        for (int facing = 0; facing < 4; facing++) {
            TrackPlan plan = TrackPlacementPlanner.plan(TrackType.VERY_LONG_STRAIGHT, facing);
            clear(helper, origin, plan);
            helper.assertTrue(
                    TrackPlacer.apply(helper.getLevel(), origin, plan).placed(),
                    "Placement failed");
            // Use a filler block well inside the piece, with rails on either side for the bogie.
            BlockPos clicked = plan.placements().stream()
                    .filter(p -> !p.gag())
                    .map(p -> origin.offset(p.dx(), p.dy(), p.dz()))
                    .findFirst().orElse(origin);
            int meta = TrackBlock.metaFromFacing(
                    helper.getLevel().getBlockState(clicked).getValue(TrackBlock.FACING));
            Placement middle = plan.placements().get(plan.size() / 2);
            clicked = origin.offset(middle.dx(), middle.dy(), middle.dz());
            for (var item : items) {
                int checked = 0;
                for (int direction = 0; direction < 8; direction++) {
                    player.setYRot(direction * 45.0F);
                    ItemStack stack = new ItemStack(item);
                    player.setItemInHand(net.minecraft.world.InteractionHand.MAIN_HAND, stack);
                    var hit = new net.minecraft.world.phys.BlockHitResult(
                            Vec3.atCenterOf(clicked), net.minecraft.core.Direction.UP, clicked, false);
                    item.useOn(new net.minecraft.world.item.context.UseOnContext(
                            player, net.minecraft.world.InteractionHand.MAIN_HAND, hit));
                    var placed = helper.getLevel().getEntitiesOfClass(
                            traincraft.vehicle.entity.RollingStockEntity.class,
                            new net.minecraft.world.phys.AABB(clicked).inflate(4));
                    // Existing placement rules can reject facing across the track.
                    for (var stock : placed) {
                        checked++;
                        float yaw = stock.getYRot();
                        float pitch = stock.getXRot();
                        String context = item + " facing=" + facing + " direction=" + direction;
                        double crossAxis = meta % 2 == 0
                                ? Math.sin(Math.toRadians(yaw)) : Math.cos(Math.toRadians(yaw));
                        helper.assertTrue(Math.abs(crossAxis) < 0.001,
                                "Incorrect spawn yaw: " + context + " yaw=" + yaw);
                        helper.assertTrue(
                                stock.tickCount == 0, "Assertion must precede first tick");
                        stock.tick();
                        helper.assertTrue(Math.abs(net.minecraft.util.Mth.wrapDegrees(stock.getYRot() - yaw)) < 0.01
                                        && Math.abs(stock.getXRot() - pitch) < 0.01,
                                "First tick changed orientation: " + context);
                        stock.discard();
                    }
                }
                helper.assertTrue(
                        checked > 0, "No placements checked for " + item + " facing=" + facing);
            }
        }
        helper.succeed();
    }

