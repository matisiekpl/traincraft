    /**
     * A cold boiler holds the locomotive still, and a lit one heats until it does not.
     *
     * <p>This is the one behaviour of the boiler that a driver meets immediately: a locomotive
     * fresh off the item is cold and will not move however hard it is driven, and stays that way
     * for a few hundred ticks. Getting it wrong in either direction is invisible in a screenshot
     * and obvious in play, so it is checked here rather than by eye.
     *
     * <p>The velocity is set along Z because a very long straight laid facing 0 runs that way, and
     * the track discards whatever is laid across it.
     */
    private static void coldLocomotiveWillNotMove(GameTestHelper helper) {
        BlockPos origin = helper.absolutePos(new BlockPos(1, 2, 1));
        TrackPlan plan = TrackPlanCatalog.get(TrackType.VERY_LONG_STRAIGHT, 0);
        if (plan != null) {
            clear(helper, origin, plan);
        }
        TrackPlacer.place(helper.getLevel(), origin, TrackType.VERY_LONG_STRAIGHT, 0);

        AliceLocomotiveEntity loco =
                helper.spawn(
                        EntityRegistry.LOCO_STEAM_ALICE.get(),
                        new Vec3(
                                1.5,
                                2.0 + traincraft.vehicle.entity.RollingStockEntity.Y_OFFSET,
                                3.5));
        loco.setItem(LocomotiveEntity.FUEL_SLOT, new ItemStack(Items.COAL, 8));
        if (loco instanceof SteamLocomotiveEntity steam) {
            steam.fillWater(1000);
        }
        // Deliberately not seeded: the point is the state it starts in.
        loco.setTemperature(0);

        helper.startSequence()
                // The fire is lit and the level climbs. One in seven ticks, so this is a handful
                // of ticks' wait, not a hundred.
                .thenWaitUntil(
                        () ->
                                helper.assertTrue(
                                        loco.getOverheatLevel() > 5,
                                        "the boiler is not heating: level="
                                                + loco.getOverheatLevel()
                                                + " fuel="
                                                + loco.getFuel()
                                                + " engine="
                                                + loco.isEngineOn()))
                .thenExecute(() -> loco.setDeltaMovement(0.0, 0.0, 0.1))
                .thenExecuteAfter(
                        2,
                        () -> {
                            helper.assertTrue(
                                    loco.getState() == HeatState.COLD,
                                    "expected a cold boiler, found "
                                            + loco.getState().displayName()
                                            + " at level "
                                            + loco.getOverheatLevel());
                            helper.assertTrue(
                                    TrackMovement.planarSpeed(loco) == 0.0,
                                    "a cold locomotive moved at "
                                            + TrackMovement.planarSpeed(loco));
                        })
                .thenExecute(() -> loco.setTemperature(loco.getAverageOverheat()))
                .thenExecuteAfter(
                        2,
                        () ->
                                helper.assertTrue(
                                        loco.getState() == HeatState.HOT,
                                        "a boiler at its average should be hot, found "
                                                + loco.getState().displayName()))
                .thenExecute(() -> loco.setDeltaMovement(0.0, 0.0, 0.1))
                .thenExecuteAfter(
                        3,
                        () ->
                                helper.assertTrue(
                                        TrackMovement.planarSpeed(loco) > 0.01,
                                        "a hot locomotive was held still at "
                                                + TrackMovement.planarSpeed(loco)))
                .thenSucceed();
    }

