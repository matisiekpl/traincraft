    private static void chme3CrossesParallelSwitch(GameTestHelper helper) {
        BlockPos origin = helper.absolutePos(new BlockPos(8, 4, 20));
        for (var segment : java.util.List.of(
                Map.entry(origin.offset(0, 0, -12), TrackType.VERY_LONG_STRAIGHT),
                Map.entry(origin, TrackType.MEDIUM_PARALLEL_SWITCH),
                Map.entry(origin.offset(3, 0, 11), TrackType.VERY_LONG_STRAIGHT))) {
            TrackPlan plan = TrackPlacementPlanner.plan(segment.getValue(), 0);
            clear(helper, segment.getKey(), plan);
            // The long approach crosses the test template's barrier wall.
            for (Placement placement : plan.placements()) {
                BlockPos rail = segment.getKey().offset(placement.dx(), placement.dy(), placement.dz());
                for (int height = 1; height <= 4; height++) {
                    helper.getLevel().setBlockAndUpdate(rail.above(height), Blocks.AIR.defaultBlockState());
                }
            }
            helper.assertTrue(TrackPlacer.apply(helper.getLevel(), segment.getKey(), plan).placed(),
                    "Could not place switch approach");
        }
        ((TrackBlockEntity) helper.getLevel().getBlockEntity(origin.offset(0, 0, 1)))
                .setSwitchActive(true);
        for (int direction : new int[] {1, -1}) {
            var loco = EntityRegistry.LOCO_DIESEL_CHME3.get().create(
                    helper.getLevel(), net.minecraft.world.entity.EntitySpawnReason.COMMAND);
            loco.setPos(origin.getX() + (direction > 0 ? 0.5 : 3.5),
                    origin.getY() + 0.85, origin.getZ() + (direction > 0 ? -4.0 : 15.0));
            loco.setYRot(direction > 0 ? 0 : 180);
            loco.alignToTrackOnPlacement();
            loco.restoreFuel(5000);
            loco.setTemperature(loco.getAverageOverheat());
            loco.setEngineOn(true);
            loco.setDeltaMovement(0, 0, direction * 0.075);
            var wagon = EntityRegistry.FREIGHT_CART_YELLOW.get().create(
                    helper.getLevel(), net.minecraft.world.entity.EntitySpawnReason.COMMAND);
            wagon.setPos(loco.getX(), loco.getY(), loco.getZ() - direction * 2.97);
            wagon.setYRot(loco.getYRot());
            wagon.alignToTrackOnPlacement();
            wagon.setDeltaMovement(loco.getDeltaMovement());
            couple(loco, wagon);
            for (int tick = 0; tick < 310; tick++) {
                // Supply steady traction while retaining the direction selected by the track.
                loco.setDeltaMovement(loco.getDeltaMovement().normalize().scale(0.075));
                loco.tick();
                wagon.tick();
                helper.assertTrue(loco.cartLinked1 == wagon && wagon.cartLinked1 == loco,
                        "Coupling broke on the switch at tick " + tick
                                + " direction=" + direction
                                + " loco=" + loco.position().subtract(Vec3.atLowerCornerOf(origin))
                                + " wagon=" + wagon.position().subtract(Vec3.atLowerCornerOf(origin)));
                helper.assertTrue(Math.abs(wagon.getY() - origin.getY() - 0.85) < 0.05,
                        "Wagon left the switch at tick " + tick);
                var bogie = loco.bogiePosition();
                double wheelbase = Math.hypot(bogie.x - loco.getX(), bogie.z - loco.getZ());
                helper.assertTrue(wheelbase > 0.6 && wheelbase < 1.8,
                        "Bogie left its locomotive at tick " + tick + ": " + wheelbase);
                helper.assertTrue(Math.abs(loco.getY() - origin.getY() - 0.85) < 0.05,
                        "Locomotive left the switch at tick " + tick);
            }
            helper.assertTrue(direction > 0 ? loco.getZ() > origin.getZ() + 11
                            : loco.getZ() < origin.getZ(),
                    "Locomotive did not cross the switch in direction " + direction
                            + " position=" + loco.position().subtract(Vec3.atLowerCornerOf(origin))
                            + " speed=" + loco.getDeltaMovement() + " engine=" + loco.isEngineOn());
            helper.assertTrue(direction > 0 ? wagon.getZ() > origin.getZ() + 11
                            : wagon.getZ() < origin.getZ(),
                    "Wagon did not follow the locomotive through the switch");
            loco.discard();
            wagon.discard();
        }
        helper.succeed();
    }

