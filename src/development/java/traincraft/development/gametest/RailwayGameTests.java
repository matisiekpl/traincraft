    /**
     * A thrown switch rewrites the rail ahead of it into the matching turn, and releasing it puts a
     * straight back. This is the routing itself: without the rewrite a train curves for the one
     * block of pointwork and is put straight again by the next rail.
     */
    private static void thrownSwitchRewritesTheRoute(GameTestHelper helper) {
        BlockPos origin = helper.absolutePos(new BlockPos(1, 2, 1));
        TrackPlan plan = TrackPlanCatalog.get(TrackType.MEDIUM_SWITCH, 0);
        if (plan == null) {
            throw new AssertionError("no plan for MEDIUM_SWITCH facing 0");
        }
        clear(helper, origin, plan);
        TrackPlacer.place(helper.getLevel(), origin, TrackType.MEDIUM_SWITCH, 0);

        BlockPos switchAt = origin.offset(0, 0, 1);
        BlockPos ahead = origin.offset(0, 0, 2);
        if (!(helper.getLevel().getBlockEntity(switchAt) instanceof TrackBlockEntity pointwork)) {
            throw new AssertionError("no rail tile at the pointwork " + switchAt);
        }
        if (!(helper.getLevel().getBlockEntity(ahead) instanceof TrackBlockEntity route)) {
            throw new AssertionError("no rail tile ahead of the switch at " + ahead);
        }
        if (route.getTrackType() != TrackType.SMALL_STRAIGHT) {
            throw new AssertionError(
                    "the rail ahead starts as "
                            + route.getTrackType()
                            + " rather than SMALL_STRAIGHT");
        }

        pointwork.setSwitchActive(true);
        if (route.getTrackType() != TrackType.MEDIUM_LEFT_TURN) {
            throw new AssertionError(
                    "a thrown switch left the rail ahead as " + route.getTrackType());
        }
        pointwork.setSwitchActive(false);
        if (route.getTrackType() != TrackType.SMALL_STRAIGHT) {
            throw new AssertionError(
                    "a released switch left the rail ahead as " + route.getTrackType());
        }
        helper.succeed();
    }

