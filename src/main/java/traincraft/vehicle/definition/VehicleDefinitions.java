    public static VehicleDefinition get(String name) {
        VehicleDefinition spec = BY_NAME.get(name);
        if (spec == null) throw new IllegalArgumentException("Unknown vehicle: " + name);
        return spec;
    }

    public static List<VehicleDefinition> all() {
        return List.copyOf(BY_NAME.values());
    }

    public static Map<String, VehicleDefinition> read(Reader reader) {
        VehicleDefinition[] definitions = new Gson().fromJson(reader, VehicleDefinition[].class);
        if (definitions == null || definitions.length == 0)
            throw new IllegalArgumentException("Empty vehicle catalog");
        Map<String, VehicleDefinition> result = new LinkedHashMap<>();
        for (VehicleDefinition definition : definitions) {
            if (result.putIfAbsent(definition.entryName(), definition) != null) {
                throw new IllegalArgumentException("Duplicate vehicle: " + definition.entryName());
            }
        }
        return Collections.unmodifiableMap(result);
    }

    private static Map<String, VehicleDefinition> load() {
        try (var stream = VehicleDefinitions.class.getResourceAsStream(RESOURCE)) {
            if (stream == null)
                throw new IllegalStateException("Missing vehicle catalog: " + RESOURCE);
            return read(new InputStreamReader(stream, StandardCharsets.UTF_8));
        } catch (java.io.IOException exception) {
            throw new IllegalStateException("Cannot load vehicle catalog", exception);
        }
    }
