    @Test
    void bakedModelsKeepTheirPartsAndLamps() throws IOException {
        for (var entry : PARTS.entrySet()) {
            try (var reader = Files.newBufferedReader(TestPaths.projectDir().resolve(
                    "src/main/resources/assets/tc/vehicle_models/" + entry.getKey() + ".json"))) {
                VehicleModel model = VehicleModel.read(reader);
                assertEquals(entry.getValue(), model.parts().size(), entry.getKey());
                assertEquals(LIT.contains(entry.getKey()),
                        model.parts().stream().anyMatch(VehicleModel.Part::emissive), entry.getKey());
                for (var part : model.parts()) {
                    assertEquals(0, part.vertices().size() % 4, part.name());
                }
            }
        }
    }

